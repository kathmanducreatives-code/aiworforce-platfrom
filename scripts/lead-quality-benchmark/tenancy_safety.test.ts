// Tests 44–48: multi-tenant + outreach/production safety.

import { assertEquals, assert, assertThrows } from "https://deno.land/std@0.224.0/assert/mod.ts";
import { assertBenchmarkPreflight } from "./env-guard.ts";
import {
  ALLOWED_LEAD_ACTIONS, assertActionAllowed, buildRunAgentEndpoint, filterRowsToWorkspace, FORBIDDEN_LEAD_ACTIONS,
} from "./live-runner.ts";
import { evaluateFixture, FIXTURES } from "./fixtures.ts";
import { DEFAULT_LIMITS, PROD_PROJECT_REF, TEST_PROJECT_REF } from "./types.ts";
import { estimateMaxCost } from "./budget.ts";

const est = estimateMaxCost(DEFAULT_LIMITS).estimatedMaxUsd;

Deno.test("44. a TEST workspace identity is required for LIVE", () => {
  const p = assertBenchmarkPreflight({
    mode: "live", projectRef: TEST_PROJECT_REF, hasSupabaseUrl: true, hasSupabaseAnonKey: true,
    hasApifyToken: true, hasWorkspaceId: false, limits: DEFAULT_LIMITS, estimatedMaxUsd: est,
  });
  assert(!p.ok);
  assert(p.blockers.some((b) => /workspace identity/i.test(b)));
});

Deno.test("45. another workspace's data is not included", () => {
  const rows = [
    { workspace_id: "ws-test", id: "a" },
    { workspace_id: "ws-other", id: "b" },
    { workspace_id: "ws-test", id: "c" },
  ];
  const scoped = filterRowsToWorkspace(rows, "ws-test");
  assertEquals(scoped.map((r) => r.id), ["a", "c"]);
});

Deno.test("46. no outreach action can be invoked", () => {
  assertThrows(() => assertActionAllowed("generate_outreach"), Error);
  assertThrows(() => assertActionAllowed("send_email"), Error);
  assertThrows(() => assertActionAllowed("start_campaign"), Error);
  assert(ALLOWED_LEAD_ACTIONS.has("source_with_apify"));
  assert(!ALLOWED_LEAD_ACTIONS.has("generate_outreach"));
  assert(FORBIDDEN_LEAD_ACTIONS.has("send_linkedin"));
});

Deno.test("47. no sendable draft is generated by an evaluation", () => {
  const e = evaluateFixture(FIXTURES.F01_valid_us_saas_sales_ops)[0];
  const keys = Object.keys(e);
  for (const forbidden of ["draft", "message", "email", "body", "sendable"]) {
    assert(!keys.includes(forbidden), `evaluation must not carry a '${forbidden}' field`);
  }
  // The outreach-angle audit only audits — it holds no message body.
  assertEquals(Object.keys(e.outreachAngle).sort(), ["angle", "connectsToValue", "ok", "referencesSignal", "violations"]);
});

Deno.test("48. no production URL is ever contacted", () => {
  assertThrows(() => buildRunAgentEndpoint(PROD_PROJECT_REF), Error);
  assertThrows(() => buildRunAgentEndpoint("unknown-ref"), Error);
  assertEquals(buildRunAgentEndpoint(TEST_PROJECT_REF), `https://${TEST_PROJECT_REF}.supabase.co/functions/v1/run-agent`);
});
