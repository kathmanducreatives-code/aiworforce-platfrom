// Generates the Workbench's DEVELOPMENT-ONLY simulation of a lead mission (MRLE).
//
//   deno run -A --no-check scripts/dev/mrle-simulation.ts
//
// Every response is produced by the REAL lead-pipeline service (plan → approval → run) in
// Mission Contract mode, offline: mocked Apify (synthetic .example companies), a fake model
// that quotes only fetched page text, an in-memory ledger. No network, no provider, no spend.
// The UI shows these only when import.meta.env.DEV and VITE_STRATEGY_DISCOVERY_MOCK=true,
// under a "Simulated data" banner. They are never real leads.

import { handleStrategyRequest } from "../../supabase/functions/_shared/leadPipeline/service.ts";
import type { StrategyPlan } from "../../supabase/functions/_shared/leadPipeline/strategy.ts";
import { deps, req } from "../../tests/edge-functions/_shared/leadPipeline/mrleFixtures.ts";

globalThis.fetch = (() => { throw new Error("network disabled"); }) as typeof fetch;
const x = deps();
const planned = await handleStrategyRequest(req({ action: "strategy_plan" }), x.d);
const plan = planned.body.plan as StrategyPlan;
const ran = await handleStrategyRequest(req({ action: "strategy_run", approval: { plan_hash: plan.planHash, apify_usd: plan.estimate.apifyUsd, token: planned.body.approval_token } }), x.d);
const blocked = await handleStrategyRequest(req({ action: "strategy_plan" }), deps({ ground: false }).d);
const reviewOnly = await handleStrategyRequest(req({ action: "strategy_plan", allow_review_only: true }), deps({ ground: false }).d);
const out = {
  simulated: true,
  note: "Generated by scripts/dev/mrle-simulation.ts from the real lead-pipeline service with mocked providers. Synthetic companies (.example). Development only.",
  plan: { status: planned.status, body: planned.body },
  run: { status: ran.status, body: ran.body },
  blockedPlan: { status: blocked.status, body: blocked.body },
  reviewOnlyPlan: { status: reviewOnly.status, body: reviewOnly.body },
};
await Deno.writeTextFile(new URL("../../src/lib/__fixtures__/strategyDiscoverySimulation.json", import.meta.url), JSON.stringify(out, null, 1) + "\n");
console.log("plan", planned.status, "run", ran.status, (ran.body.outcome as { status: string })?.status, "blocked", blocked.status, "reviewOnly", reviewOnly.status);
